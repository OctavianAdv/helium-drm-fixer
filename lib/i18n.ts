export const LANGUAGES = { en, ro, es, de, fr, pt, it, ru } as const;
export type Lang = keyof typeof LANGUAGES;
export const LANGUAGE_NAMES: Record<Lang, string> = {
  en: "English",
  ro: "Română",
  es: "Español",
  de: "Deutsch",
  fr: "Français",
  pt: "Português",
  it: "Italiano",
  ru: "Русский",
};

let current: Lang = "en";

function asLang(value: string | undefined | null): Lang | null {
  const code = value?.trim().toLowerCase().slice(0, 2);
  return code && code in LANGUAGES ? (code as Lang) : null;
}

function systemLanguage(): string | null {
  try {
    if (process.platform === "win32") {
      const out = execFileSync("reg", ["query", "HKCU\\Control Panel\\International", "/v", "LocaleName"], {
        encoding: "utf-8",
        windowsHide: true,
        stdio: ["ignore", "pipe", "ignore"],
      });
      return out.match(/LocaleName\s+REG_SZ\s+(\S+)/)?.[1] ?? null;
    }
    if (process.platform === "darwin") {
      const out = execFileSync("defaults", ["read", "-g", "AppleLanguages"], {
        encoding: "utf-8",
        stdio: ["ignore", "pipe", "ignore"],
      });
      return out.match(/"?([a-zA-Z]{2})[-_"]/)?.[1] ?? null;
    }
  } catch {
    // fall through
  }
  return null;
}

/** Pick the language: explicit choice, then the OS setting, then the environment. */
export function detectLanguage(explicit?: string): Lang {
  const env = process.env;
  const linuxEnv = [env.LC_ALL, env.LC_MESSAGES, env.LANG, env.LANGUAGE?.split(":")[0]].filter(
    (v) => v && !/^(C|POSIX)([._]|$)/.test(v)
  );
  const candidates =
    process.platform === "linux"
      ? [explicit, env.HELIUM_DRM_FIXER_LANG, ...linuxEnv]
      : [explicit, env.HELIUM_DRM_FIXER_LANG, systemLanguage(), ...linuxEnv];
  candidates.push(Intl.DateTimeFormat().resolvedOptions().locale);
  for (const candidate of candidates) {
    const lang = asLang(candidate);
    if (lang) return lang;
  }
  return "en";
}

export function setLanguage(lang: Lang): void {
  current = lang;
}

export function getLanguage(): Lang {
  return current;
}

/** Translate a message, filling in {placeholders}. */
export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  const text = LANGUAGES[current][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

/** Every message in the current language (for the window version). */
export function allMessages(): Record<MessageKey, string> {
  return { ...en, ...LANGUAGES[current] } as Record<MessageKey, string>;
}
